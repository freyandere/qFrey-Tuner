export type RestoreMessageKey = keyof typeof enRestoreMessages;

export function translateRestore(locale: Locale, key: string, parameters: Readonly<Record<string, string | number>> = {}): string {
  const dictionary = locale === 'ru-RU' ? ruRestoreMessages : enRestoreMessages;
  const template = Object.hasOwn(dictionary, key) ? dictionary[key as RestoreMessageKey] : dictionary['restore.unknown'];
  return template.replace(/\{(\w+)\}/g, (_match, name: string) => String(parameters[name] ?? '—'));
}
