export function translateHardware(locale: Locale, key: string, parameters: Readonly<Record<string, string | number>> = {}): string {
  const messages = locale === 'ru-RU' ? ruHardwareMessages : enHardwareMessages;
  const template = Object.hasOwn(messages, key) ? messages[key as keyof typeof enHardwareMessages] : messages['hardware.reason.generic'];
  return template.replace(/\{(\w+)\}/g, (_match, name: string) => String(parameters[name] ?? '—'));
}

export function translateHardwareStage(locale: Locale, stage: string): string {
  const known: Record<string, string> = { hardwareDetection: 'hardware.detecting', completing: 'hardware.detecting' };
  return translateHardware(locale, known[stage] ?? 'hardware.detecting');
}
