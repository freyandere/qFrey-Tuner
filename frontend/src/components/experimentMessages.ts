type ExperimentMessageKey = keyof typeof enExperimentMessages;
export function translateExperiment(locale: Locale, key: string, parameters: Record<string, string | number> = {}): string {
  const template = (locale === 'ru-RU' ? ruExperimentMessages : enExperimentMessages)[key as ExperimentMessageKey]
    ?? (locale === 'ru-RU' ? ruExperimentMessages['experiment.localeFallback'] : enExperimentMessages['experiment.localeFallback']);
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (_, name: string) => String(parameters[name] ?? ''));
}

export function parseExistingHashes(value: string): { hashes: string[]; valid: boolean } {
  const hashes = value.trim().split(/\s+/).filter(Boolean).map(hash => hash.toLowerCase());
  const unique = new Set(hashes);
  return { hashes, valid: hashes.length >= 1 && hashes.length <= 5000 && unique.size === hashes.length && hashes.every(hash => /^[0-9a-f]{40}$/.test(hash)) };
}

export function translateExperimentStage(locale: Locale, stage: string): string {
  const normalized = stage.trim().replace(/([a-z])([A-Z])/g, '$1 $2').toLowerCase().replace(/[^a-z0-9]+/g, '');
  const code = ({ warmup: 'warmingUp', warmingup: 'warmingUp', baselinewarmup: 'warmingUp', baselinesampling: 'sampling', sampling: 'sampling', baseline: 'baseline',
    measuring: 'measuring', completing: 'completing', starting: 'starting', cancelling: 'cancelling' } as Record<string, string>)[normalized];
  return translateExperiment(locale, code ? `experiment.operation.stage.${code}` : 'experiment.operation.stage.unknown');
}
