export type ResultMessageKey = keyof typeof enResultMessages;

export function resultMessage(locale: Locale, key: string, parameters: Readonly<Record<string, string | number>> = {}): string {
  const local = (locale === 'ru-RU' ? ruResultMessages : enResultMessages) as Readonly<Record<string, string>>;
  const fallback = local['results.unknownText'];
  const template = local[key] ?? (Object.hasOwn(en, key) ? translate(locale, key, parameters) : fallback);
  return local[key] === undefined ? template : template.replace(/\{(\w+)\}/g, (_match, name: string) => {
    const value = parameters[name];
    return typeof value === 'number' && Number.isFinite(value) ? formatNumber(locale, value)
      : typeof value === 'string' ? value : '—';
  });
}

export function resultReason(locale: Locale, code: string): string {
  const key = `results.reason.${code}`;
  const local = (locale === 'ru-RU' ? ruResultMessages : enResultMessages) as Readonly<Record<string, string>>;
  return local[key] ?? resultMessage(locale, 'results.unknownText');
}

export function resultUnitKey(unit: MetricUnit): ResultMessageKey { return `results.unit.${unit}` as ResultMessageKey; }
export function resultScopeKey(scope: MetricScope): ResultMessageKey { return `results.scope.${scope}` as ResultMessageKey; }
