export function translate(locale: Locale, key: string, parameters: Readonly<Record<string, string | number>> = {}): string {
  const dictionary = locale === 'ru-RU' ? ru : en;
  const template = Object.hasOwn(dictionary, key) ? dictionary[key as TranslationKey] : dictionary['errors.unknown'];
  const values = key.startsWith('calculator.') ? localizeCalculatorParameters(locale, parameters) : parameters;
  return template.replace(/\{(\w+)\}/g, (_match, name: string) => {
    const value = values[name];
    return typeof value === 'number' && Number.isFinite(value) ? formatNumber(locale, value) : typeof value === 'string' ? value : '—';
  });
}
export function parseDecimal(text: string): number | null {
  const normalized = text.trim();
  // Accept one decimal mark, but no grouping, exponent, or partial decimals.
  if (!/^[+-]?\d+(?:[.,]\d+)?$/.test(normalized)) return null;
  const value = Number(normalized.replace(',', '.'));
  return Number.isFinite(value) ? value : null;
}

export function formatNumber(locale: Locale, value: number, options?: Intl.NumberFormatOptions): string {
  return new Intl.NumberFormat(locale, options).format(value);
}

export function formatDate(locale: Locale, value: Date | number, options?: Intl.DateTimeFormatOptions): string {
  return new Intl.DateTimeFormat(locale, options).format(value);
}

export type PluralForms = Readonly<Partial<Record<Intl.LDMLPluralRule, string>> & { other: string }>;

export function pluralCategory(locale: Locale, value: number): Intl.LDMLPluralRule {
  return new Intl.PluralRules(locale).select(value);
}

export function formatPlural(locale: Locale, value: number, forms: PluralForms): string {
  return forms[pluralCategory(locale, value)] ?? forms.other;
}
